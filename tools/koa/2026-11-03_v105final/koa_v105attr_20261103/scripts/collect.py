#!/usr/bin/env python3
"""collect.py: metrics of every attribution run (and v105d / v105c at SDImax 923 for reference, read only) from their output files.
Writes out/metrics_long.csv (run, metric, value, source file), out/metrics_wide.csv, out/bakuzis_flags_by_run.csv, out/attribution.csv."""
import os, re, json, numpy as np, pandas as pd
J = os.path.expanduser("~/jobs/koa_v105attr_20261103"); O = f"{J}/out"; os.makedirs(O, exist_ok=True)
D5D = os.path.expanduser("~/jobs/koa_v105d_20261102"); D5C = os.path.expanduser("~/jobs/koa_v105c_20261102")
RUNS = [r for r in ("D742", "R_dHT", "R_HT", "R_HCB", "R_S3", "P_HT_HCB", "C742") if os.path.exists(f"{J}/{r}/a5/rerun/cov/cov_v105d.log") or True]
SRC = {r: f"{J}/{r}" for r in RUNS}; SRC.update({"v105d@923": D5D, "v105c@923": D5C})
rows = []
def add(run, metric, value, src): rows.append(dict(run=run, metric=metric, value=value, source=src))
STALE = []
for run, W in SRC.items():
    T0 = os.path.getmtime(f"{J}/logs/{run}/deploy.log") if run in RUNS and os.path.exists(f"{J}/logs/{run}/deploy.log") else None
    def ok(p):
        if not os.path.exists(p): return False
        if T0 is not None and os.path.getmtime(p) < T0: STALE.append((run, p)); return False   # copied v105d output not regenerated by this run
        return True
    p = f"{W}/engine_v103/out_m1/table8_evenaged_M1.csv"
    if ok(p):
        T = pd.read_csv(p); T = T[T.Age == 40]
        for r in T.itertuples():
            for q in ("VOL", "QMD"): add(run, f"{q}40 | {r.Scenario} | {r.Site}", f"{getattr(r, q):.1f} ({getattr(r, q + '_lo'):.1f} to {getattr(r, q + '_hi'):.1f})", "engine_v103/out_m1/table8_evenaged_M1.csv")
    p = f"{W}/a4/culmination_mc_v104.json"
    if ok(p):
        for k, v in json.load(open(p)).items(): add(run, f"culmination pt | {k}", v["pt_window"], "a4/culmination_mc_v104.json"); add(run, f"culmination MC | {k}", v["med_window"], "a4/culmination_mc_v104.json")
    p = f"{W}/a4/bakuzis/bakuzis_checks_v104_v105.csv"
    if ok(p):
        B = pd.read_csv(p); B = B[B.version == "v105"]
        vc = B.result.value_counts().to_dict()
        for k in ("PASS", "FLAG", "info", "NOT EVALUATED"): add(run, f"Bakuzis {k}", vc.get(k, 0), "a4/bakuzis/bakuzis_checks_v104_v105.csv")
        add(run, "Bakuzis evaluated", vc.get("PASS", 0) + vc.get("FLAG", 0), "a4/bakuzis/bakuzis_checks_v104_v105.csv")
        add(run, "Bakuzis Reineke step", ";".join(sorted(set(re.findall(r"step ([0-9.]+)", " ".join(B.value.astype(str)))))) or "none in values", "a4/bakuzis/bakuzis_checks_v104_v105.csv")
        for r in B[B.relation == "Eichhorn"].itertuples():
            m = re.search(r"median ([0-9.]+)%, max ([0-9.]+)%", str(r.value))
            add(run, f"Eichhorn median CV % | {r.group}", m.group(1) if m else r.value, "a4/bakuzis/bakuzis_checks_v104_v105.csv"); add(run, f"Eichhorn max CV % | {r.group}", m.group(2) if m else "", "a4/bakuzis/bakuzis_checks_v104_v105.csv")
            add(run, f"Eichhorn result | {r.group}", r.result, "a4/bakuzis/bakuzis_checks_v104_v105.csv"); add(run, f"Eichhorn height range | {r.group}", r.item, "a4/bakuzis/bakuzis_checks_v104_v105.csv")
        B[["group", "relation", "item", "value", "result"]].assign(run=run).to_csv(f"{O}/bakuzis_rows_{run.replace('@', '_')}.csv", index=False)
    p = f"{W}/a2/closeout/validation/val_v104_plotlevel.csv"
    if ok(p):
        V = pd.read_csv(p); V = V[V.pid != "FIA|15-1-1-2628"]
        for s, g in list(V.groupby("source")) + [("all", V)]:
            for q, o, pr in (("QMD", "obsQMD", "prQMD"), ("BA", "obsBAPH", "prBAPH")):
                e = g[pr] - g[o]; add(run, f"plot-level {q} bias / RMSE | {s} (n {len(g)})", f"{e.mean():.3f} / {np.sqrt((e ** 2).mean()):.3f}", "a2/closeout/validation/val_v104_plotlevel.csv")
    p = f"{W}/a4/lt/LT_v104_points.csv"
    if ok(p):
        V = pd.read_csv(p)
        for s, g in list(V.groupby("source")) + [("all", V)]:
            for q, o, pr in (("QMD", "obsQMD", "prQMD"), ("BA", "obsBAPH", "prBAPH")):
                e = g[pr] - g[o]; add(run, f"trajectory {q} bias / RMSE | {s} (n {len(g)})", f"{e.mean():.3f} / {np.sqrt((e ** 2).mean()):.3f}", "a4/lt/LT_v104_points.csv")
    p = f"{W}/a5/rerun/cov/tableS26_coverage_v104.csv" if run != "v105c@923" else f"{D5D}/a5/rerun/cov_v105c/tableS26_coverage_v104.csv"
    if ok(p):
        C = pd.read_csv(p)
        for r in C[(C.unitset == "plotlevel") & (C.variable.isin(["BA", "QMD"]))].itertuples(): add(run, f"coverage plotlevel {r.variable} | {r.group}", f"{r.coverage:.3f}", p.replace(W + "/", "").replace(D5D + "/", "koa_v105d_20261102/"))
    if run in RUNS: p = f"{W}/v105d/out/realism_{run}.csv"
    else: p = f"{D5D}/v105d/out/realism_{run.split('@')[0]}.csv"
    if ok(p):
        R = pd.read_csv(p); S = R[R.kind == "suppressed"]
        for c in ("dht_d_density", "dht_d_share", "ddbh_d_density", "ddbh_d_share"): add(run, f"realism suppressed positive | {c}", f"{int((S[c] > 1e-12).sum())} of {len(S)}", os.path.relpath(p, W) if p.startswith(W) else p)
        add(run, "realism RD max in projections", f"{R.RD.max():.3f}", os.path.relpath(p, W) if p.startswith(W) else p)
    p = f"{W}/out/v105_constants.json"
    if ok(p):
        mc = json.load(open(p)).get("MORT_CAL", {}).get("value"); add(run, "MORT_CAL natural", mc[0] if mc else "", "out/v105_constants.json")
if os.path.exists(f"{O}/eichhorn_exact.csv"):   # unrounded Eichhorn CVs (scripts/eichhorn_exact.R, same computation as the Bakuzis script)
    for r in pd.read_csv(f"{O}/eichhorn_exact.csv").itertuples(): add(r.run, f"Eichhorn median CV % unrounded | {r.group}", round(r.median_cv, 4), "out/eichhorn_exact.csv")
L = pd.DataFrame(rows); L.to_csv(f"{O}/metrics_long.csv", index=False)
order = [r for r in RUNS] + ["v105d@923", "v105c@923"]
Wd = L.pivot_table(index="metric", columns="run", values="value", aggfunc="first")[[c for c in order if c in set(L.run)]]; Wd.to_csv(f"{O}/metrics_wide.csv")
print(Wd.to_string()); print("STALE (not regenerated, skipped):", STALE)
